'use strict';
// ONE tunnel, one connector, one config file — pinned, because the opposite is silent.
//
// The second tunnel (a3af5bb4, build-tukuk) did not fail loudly: it worked, so it stayed. What it
// cost was a credential only the identity archive had, a unit that had to be installed and started
// on every rebuild, and one hostname group that 530'd whenever that unit was forgotten. Nothing in
// the test suite objected, because nothing was looking. These assertions are the thing that looks.
//
// The layer that actually decides routing on this box is the Cloudflare dashboard (token-mode
// tunnels ignore the local ingress), so this file cannot prove the edge is right. It proves the
// repo cannot quietly grow a second connector again, and that the canonical list in the repo is
// complete — scripts/cloudflared-audit.js compares that list with the live edge.
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const CF_DIR = path.join(ROOT, 'deploy', 'cloudflared');
const read = (...p) => fs.readFileSync(path.join(ROOT, ...p), 'utf8');

const CONFIG = read('deploy', 'cloudflared', 'config.yml');
const HOSTS = CONFIG.split('\n')
  .map((l) => l.match(/^\s*-\s*hostname:\s*(\S+)\s*$/))
  .filter(Boolean)
  .map((m) => m[1]);

test('this box has exactly one connector config, and the mirror is not it', () => {
  // gcp-config.yml is deliberate and different in kind: it is installed on a Google Cloud VM in
  // another provider, precisely so a home-box blackout cannot take the mirror down with it. The
  // rule this file enforces is "one connector on THIS box" — not "one tunnel on the planet".
  // config.frozen.yml is not a second connector either: it is the TOKENLESS snapshot of the
  // SAME tunnel c1d8ea0f — the exact three-hostname, token-mode shape the live box holds
  // (owner freeze, 2026-11-01), kept so a rebuild can never invent a fourth hostname back.
  // Its `tunnel-token` line is a placeholder; the live value lives only on the box.
  const files = fs.readdirSync(CF_DIR).filter((f) => /\.ya?ml$/i.test(f)).sort();
  assert.deepEqual(files, ['config.frozen.yml', 'config.yml', 'gcp-config.yml'],
    'a third config file is a third connector waiting to be installed');
  const frozen = read('deploy', 'cloudflared', 'config.frozen.yml');
  assert.match(frozen, /c1d8ea0f/, 'the frozen snapshot must name the ONE real tunnel');
  assert.doesNotMatch(frozen, /tunnel-token:\s*\S*eyJ/,
    'the frozen snapshot ships TOKENLESS — a connector token in git can point tukuk.org anywhere');
  const setup = read('scripts', 'setup-all.sh');
  assert.doesNotMatch(setup, /gcp-config/,
    'the mirror config belongs to the VM; installing it here would give this box a second ingress');
  const mirror = read('deploy', 'cloudflared', 'gcp-config.yml');
  assert.match(mirror, /SEPARATE tunnel/, 'the mirror config must say out loud that it is another machine');
});

test('deploy/ ships no second connector unit', () => {
  const units = fs.readdirSync(path.join(ROOT, 'deploy')).filter((f) => /^cloudflared-.*\.service$/.test(f));
  assert.deepEqual(units, [], 'cloudflared-*.service means a second connector; routes belong on cloudflared.service');
  const tunnelRuns = fs.readdirSync(path.join(ROOT, 'deploy'))
    .filter((f) => f.endsWith('.service'))
    .filter((f) => /tunnel\s+run/.test(fs.readFileSync(path.join(ROOT, 'deploy', f), 'utf8')));
  assert.deepEqual(tunnelRuns, [], 'the connector unit is generated by setup-all.sh; a copy in deploy/ is what drifted last time');
});

test('every hostname is a route on the one tunnel, listed once', () => {
  const expected = ['tukuk.org', 'www.tukuk.org', 'tchat.tukuk.org', 'agent.tukuk.org', 'play.tukuk.org', 'build.tukuk.org'];
  for (const host of expected) {
    assert.equal(HOSTS.filter((h) => h === host).length, 1, `${host} must appear exactly once in config.yml`);
  }
  assert.equal(new Set(HOSTS).size, HOSTS.length, 'a duplicated hostname silently shadows the earlier rule');
});

test('the retired dashboard hostname stays retired', () => {
  // It served the same app on the same port as the apex, where /admin already lives. Re-adding it
  // means a second DNS record, a second WEBAUTHN_ORIGIN and a login page that can 502 by itself.
  assert.ok(!HOSTS.includes('dashboard.tukuk.org'), 'dashboard.tukuk.org is gone: the panel is /admin on tukuk.org');
  assert.doesNotMatch(read('deploy', 'env.defaults'), /dashboard\.tukuk\.org/,
    'a stale WebAuthn origin is how the deleted hostname comes back as a login failure');
});

test('the catch-all is last, and it answers 404 rather than 502', () => {
  const lines = CONFIG.split('\n').map((l) => l.trim()).filter(Boolean);
  const last = lines[lines.length - 1];
  assert.equal(last, '- service: http_status:404', 'cloudflared uses the first matching rule; a catch-all above a hostname deletes it');
});

test('nothing in the repo can recreate the second connector by accident', () => {
  // The retired identifiers may appear in prose (the history is worth keeping) but never as a
  // variable that setup-all.sh or a script would act on.
  for (const file of ['scripts/setup-all.sh', '.env.example', 'deploy/env.defaults']) {
    const src = read(...file.split('/'));
    assert.doesNotMatch(src, /CF_BUILD_TUNNEL_[A-Z]+=/, `${file} must not define a second-tunnel credential`);
  }
  assert.doesNotMatch(read('scripts', 'setup-all.sh'), /config-build\.example/,
    'the retired template is gone; a reference to it would fail at install time');
  assert.doesNotMatch(read('scripts', 'watchdog.sh'), /cloudflared-build/,
    'the watchdog must restart cloudflared.service, not a unit that no longer exists');
});

test('the build route points at the wake front door, not the builder itself', () => {
  // :5176 is the builder, :5174 is the front door that wakes it. Pointing the tunnel at 5176 turns
  // "builder idle-stopped" into a Cloudflare 502 instead of a warming page.
  const block = CONFIG.split('- hostname: build.tukuk.org')[1] || '';
  assert.match(block.split('- hostname:')[0], /service:\s*http:\/\/127\.0\.0\.1:5174/,
    'build.tukuk.org must front :5174 (tukuk-builder-wake), never :5176');
});
